#!/usr/bin/env python3
"""One-shot: rewrite RACiT's BCUS98124 guest addresses to BCES00511.

Inputs are game/hot_ppu.h (USA function starts) and the function list the
loader made from the EU ELF (out/EBOOT.functions.json). A Viterbi pass picks the
offset of each USA function so it lands on an EU function start, with as few
offset changes as possible. Offsets of data and SPU blobs were measured
separately (see CLAUDE.md). Writes scripts/addr_map_usa_eu.tsv and, with
--apply, rewrites the sources. Run once, on the untouched USA sources.
"""
import bisect, json, os, re, subprocess, sys
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
os.chdir(ROOT)
FILES = ['game/stubs.cpp', 'game/main.cpp', 'game/hot_ppu.h', 'scripts/patch_lift.py',
         'scripts/fix_vmx_alias.py', 'scripts/name_pass.py', 'scripts/lift_spu_jobs.py',
         'scripts/lift_policy_modules.py', 'scripts/find_submodules.py', 'game/hot_spu_modules.cmake',
         'scripts/spu_submodules.txt']
# Other games' addresses quoted in comments of the runtime patch: not ours.
FOREIGN = {0x26DE0, 0x272AC, 0x3F904, 0x3F90C, 0x750A8, 0xE90B4, 0x3319D0}
SPU_LO, SPU_HI, SPU_D = 0xAD0000, 0xC20000, 0x800     # SPU code, end of segment 0
BSS_LO, BSS_HI, BSS_D = 0xDB0000, 0xFD0000, 0x100     # data tail, bss
POOL = {0xD2FAA4: 0xC0, 0xD2F988: 0xC0}               # measured on the EU ELF

src = {f: open(f, encoding='utf8', newline='').read() for f in FILES}
f = json.load(open('out/EBOOT.functions.json'))
starts = sorted({int(x['start'], 16) for x in (f.get('functions', f) if isinstance(f, dict) else f)})
us = set()
for t in src.values():
    us |= {int(x, 16) for x in re.findall(r'func_([0-9A-Fa-f]{8})\b', t)}
us = sorted(a for a in us - FOREIGN if a < 0xA50000)
cands = [[s - a for s in starts[bisect.bisect_left(starts, a - 0x40):bisect.bisect_left(starts, a + 0x800)]] or [None] for a in us]
cost, back = [{d: 0 for d in cands[0]}], [{}]
for i in range(1, len(us)):
    cur, bk = {}, {}
    for d in cands[i]:
        best, bp = 1 << 40, None
        for p, c in cost[-1].items():
            t = c + (3 if d is None else 0)
            if d is not None and p is not None and d != p:
                t += 7 if d < p else 2
            if t < best:
                best, bp = t, p
        cur[d], bk[d] = best, bp
    cost.append(cur); back.append(bk)
d = min(cost[-1], key=cost[-1].get)
path = [d]
for i in range(len(us) - 1, 0, -1):
    d = back[i][d]; path.append(d)
path.reverse()
fmap = {a: d for a, d in zip(us, path) if d is not None}
known = sorted(fmap)
ambiguous = set()

def code(a):
    if a in fmap: return a + fmap[a]
    i = bisect.bisect_right(known, a) - 1
    if i < 0: return a
    lo, hi = fmap[known[i]], fmap[known[min(i + 1, len(known) - 1)]]
    if lo != hi: ambiguous.add(a)
    return a + lo          # inside the lower neighbour's stretch

def conv(a):
    if a in POOL: return a + POOL[a]
    if 0x10000 <= a < 0xA50000: return code(a)
    if SPU_LO <= a < SPU_HI: return a + SPU_D
    if BSS_LO <= a < BSS_HI: return a + BSS_D
    return None

hits = {}
skipped = set()
def sub(m):
    pre, h, post = m.group(1), m.group(2), m.group(3) or ''
    a = int(h, 16)
    n = conv(a)
    if n is None: return m.group(0)
    hits[a] = n
    return pre + (('%0' + str(len(h)) + 'X') % n) + post

def lit(m):
    a = int(m.group(2), 16)
    if a < 0x10000 or a & 0xFFF in (0, 0xFFF):
        skipped.add(m.group(0))
        return m.group(0)
    return sub(m)

bare_seen = []
for name, t in src.items():
    n = re.sub(r'\b(func_|loc_)([0-9A-Fa-f]{8})\b()', sub, t)
    n = re.sub(r'\b(job_|sub_)([0-9A-F]{6})(_|\b)', sub, n)
    n = re.sub(r'\b(spu_\d{4}_at_00)([0-9A-F]{6})\b()', sub, n)
    n = re.sub(r'\b(0x00)([0-9A-Fa-f]{6})(u?)\b', lit, n)
    bare = r'(?<![0-9A-Za-z_])(0x)([0-9A-F]{5,6})(u?)\b'
    if name == 'scripts/name_pass.py':
        n = re.sub(bare, lit, n)
    elif name in ('scripts/lift_spu_jobs.py', 'scripts/lift_policy_modules.py', 'scripts/find_submodules.py'):
        n = re.sub(bare, lambda m: lit(m) if int(m.group(2), 16) >= SPU_LO else m.group(0), n)
    elif name in ('game/stubs.cpp', 'game/main.cpp', 'scripts/patch_lift.py'):
        def noted(m):
            r = lit(m)
            if r != m.group(0): bare_seen.append((name, m.group(0), r))
            return r
        n = re.sub(r'(?<![0-9A-Za-z_])(0x)([0-9A-F]{6})(u?)\b', noted, n)
    if name == 'scripts/spu_submodules.txt':
        n = re.sub(r'(?m)^()([0-9A-F]{6})( )', sub, t)
    src[name] = n
with open('scripts/addr_map_usa_eu.tsv', 'w', newline='\n') as o:
    o.write('# BCUS98124 -> BCES00511, generated by scripts/dev/port_addresses.py\n# usa\teu\n')
    for a in sorted(hits):
        o.write('%08X\t%08X\n' % (a, hits[a]))
print(*bare_seen, sep=chr(10))
print(len(hits), 'addresses;', 'ambiguous:', [hex(a) for a in sorted(ambiguous)])
print('skipped', sorted(skipped))
if '--apply' in sys.argv:
    for name, t in src.items():
        open(name, 'w', encoding='utf8', newline='').write(t)
